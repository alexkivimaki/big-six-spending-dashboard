export function getMetricFormulaText(metricId, valueBasis = VALUE_BASIS.nominal) {
  const metric = getMetric(metricId);
  if (!metric) return "";
  if (metric.format === "percentage" && valueBasis === VALUE_BASIS.inflationAdjusted) {
    return metric.inflationBehavior ?? metric.formulaLabel;
  }
  return metric.formulaLabel;
}
